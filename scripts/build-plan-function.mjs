// Generates the SINGLE-FILE supabase/functions/plan/index.ts (easy to paste into the Supabase dashboard) from core.mjs + the Deno wiring below.
import { readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('../supabase/functions/plan/', import.meta.url);
export const WIRING = `
// ---- Deno / Supabase wiring (secrets come from the function's environment; never from code) ----
const admin = createClient(Deno.env.get('SUPABASE_URL'), Deno.env.get('SUPABASE_SERVICE_ROLE_KEY'), { auth: { persistSession: false } });
const allowedOrigins = (Deno.env.get('ALLOWED_ORIGINS') || 'https://dannyekusu.github.io,http://localhost:8080').split(',').map(s => s.trim()).filter(Boolean);
async function callModel(messages) {
  const base = (Deno.env.get('AI_BASE_URL') || '').replace(/\\/$/, ''), key = Deno.env.get('AI_API_KEY'), model = Deno.env.get('AI_MODEL');
  if (!base.startsWith('https://') || !key || !model) throw new Error('AI provider is not configured');
  const ctl = new AbortController(), timer = setTimeout(() => ctl.abort(), 20000);
  try {
    const res = await fetch(base + '/chat/completions', { method: 'POST', signal: ctl.signal, headers: { 'Content-Type': 'application/json', Authorization: 'Bearer ' + key },
      body: JSON.stringify({ model, messages, temperature: 0.2, max_tokens: 1500, response_format: { type: 'json_object' } }) });
    if (!res.ok) throw new Error('provider ' + res.status);
    return (await res.json()).choices?.[0]?.message?.content ?? '';
  } finally { clearTimeout(timer); }
}
async function prefs(id) {   // works before and after migration 0007 (ai_share_data may not exist yet)
  let r = await admin.from('preferences').select('ai_opt_in,ai_share_data').eq('user_id', id).maybeSingle();
  if (r.error) r = await admin.from('preferences').select('ai_opt_in').eq('user_id', id).maybeSingle();
  if (r.error) throw r.error; return r.data || {};
}
Deno.serve(req => handlePlan(req, {
  allowedOrigins, dailyLimit: Number(Deno.env.get('AI_DAILY_LIMIT') || 20),
  getUser: async token => { const { data, error } = await admin.auth.getUser(token); return error ? null : data.user; },
  hasOptedIn: async id => !!(await prefs(id)).ai_opt_in,
  sharesData: async id => !!(await prefs(id)).ai_share_data,
  consume: async (id, limit) => { const { data, error } = await admin.rpc('ai_consume', { p_user: id, p_limit: limit }); if (error) throw error; return data === true; },
  callModel }));
`;
export const build = () => "// GENERATED by scripts/build-plan-function.mjs from core.mjs: edit core.mjs, then run `node scripts/build-plan-function.mjs`.\nimport { createClient } from 'npm:@supabase/supabase-js@2';\n" + readFileSync(new URL('core.mjs', dir), 'utf8').replace(/^export /gm, '') + WIRING;
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) { writeFileSync(new URL('index.ts', dir), build()); console.log('wrote supabase/functions/plan/index.ts'); }
